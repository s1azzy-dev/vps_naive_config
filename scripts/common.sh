#!/usr/bin/env bash
set -Eeuo pipefail

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
ROOT_DIR=$(cd -- "$SCRIPT_DIR/.." && pwd -P)

die() {
  printf 'ERROR: %s\n' "$*" >&2
  exit 1
}

require_command() {
  command -v "$1" >/dev/null 2>&1 || die "required command not found: $1"
}

load_project_env() {
  RUNTIME_ENV="/etc/naive-gateway/gateway.env"
  if [[ -f "$ROOT_DIR/.runtime-env-path" ]]; then
    IFS= read -r RUNTIME_ENV < "$ROOT_DIR/.runtime-env-path"
  fi
  [[ -f "$RUNTIME_ENV" ]] || die "runtime environment not found; complete deployment first"
  # shellcheck source=../versions.env
  # shellcheck disable=SC1091
  source "$ROOT_DIR/versions.env"
  # The runtime file is generated by this project with shell-safe values.
  # shellcheck source=/dev/null
  source "$RUNTIME_ENV"
}

compose() {
  local extra_files=()
  if [[ -f "$ROOT_DIR/deployment.yml" ]]; then
    extra_files=(-f "$ROOT_DIR/deployment.yml")
  fi
  env -u DOMAIN -u ACME_EMAIL -u NAIVE_USER -u NAIVE_PASSWORD \
    -u CADDY_VERSION -u FORWARDPROXY_COMMIT docker compose \
    --env-file "$ROOT_DIR/versions.env" \
    --env-file "$RUNTIME_ENV" \
    --project-directory "$ROOT_DIR" \
    -f "$ROOT_DIR/compose.yml" "${extra_files[@]}" "$@"
}

random_hex() {
  local bytes=$1
  openssl rand -hex "$bytes"
}
